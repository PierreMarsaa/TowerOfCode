/**
 * Overworld sprites in the Pokémon Gold/Silver/Crystal style, drawn as ASCII.
 *
 * Each character is a 128×128 sheet of 4×4 frames of 32×32 (src/utils/AnimationFactory.ts):
 * rows down, left, right, up; columns idle, step A, idle, step B (the walk plays 1, 0, 3, 0).
 * The 16×16 figure sits at x 8..23, y 12..27 of its frame: feet on row 27, 4 px above the
 * tile like GSC. Figures use at most 3 colours + transparency: '1' light (skin and white
 * cloth), '2' main, '3' dark (outline, eyes, black hair and clothes), '.' transparent.
 *
 * Source format: a direction is a head (rows shared by all its frames, so the head never
 * moves while walking) plus bodies for idle and step (the remaining rows). An 8-char row is
 * the left half of a symmetric row. Down/up step B is the step A body mirrored (head left
 * untouched) unless drawn as `stepB` (Prof Pi's satchel); left step B = step A, as in GSC.
 * Right = left mirrored. `still` is one frame used for all 16 (items).
 */
import { Bitmap, hex } from '../bitmap.mjs'
import { OBJ, spriteColors, fromAscii, mirrorRows, checkSprite } from './palette.mjs'

const pal = (...cs) => cs.map(hex)

/** Local palettes, in OBJ's [light, main, dark] format */
const ELDER = pal('#f8d8b0', '#8890a0', '#181010') // grey, with a skin-tone light (OBJ.gray's is white)
const BALL = pal('#f8f8f8', '#30a0a0', '#181010') // white, teal, black

/** An 8-char row is the left half of a symmetric row; 16-char rows are taken as is */
const sym = r => (r.length === 8 ? r + [...r].reverse().join('') : r)
const F = rows => rows.map(sym)

/** [idle, step A, step B] frames of one direction */
function view({ head, idle, step, stepB }, side = false) {
  const h = F(head)
  const b0 = F(idle), b1 = F(step ?? idle)
  const b2 = stepB ? F(stepB) : side ? b1 : mirrorRows(b1)
  return [h.concat(b0), h.concat(b1), h.concat(b2)]
}

function character(palette, { down, up, left, still }) {
  if (still) {
    const frames = [F(still), F(still), F(still)]
    return { palette, still: true, down: frames, up: frames, left: frames }
  }
  return { palette, down: view(down), up: view(up), left: view(left, true) }
}

