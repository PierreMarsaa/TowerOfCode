export const CHARACTERS = Object.fromEntries(
  Object.entries(SRC).map(([key, [palette, views]]) => [key, character(palette, views)]),
)

// ── Sheets ──

/** Sheet rows (top → bottom) and the frame shown in each column (idle, step A, idle, step B) */
const SHEET_ROWS = ['down', 'left', 'right', 'up']
const FRAME_OF_COLUMN = [0, 1, 0, 2]
/** Where the 16×16 figure sits inside its 32×32 frame (feet on row 27, like GSC's 4-px lift) */
const FIG_X = 8, FIG_Y = 12

/** Right = left mirrored, except for still items (identical in every frame) */
function framesOf(spec, dir) {
  if (dir !== 'right') return spec[dir]
  return spec.still ? spec.left : spec.left.map(mirrorRows)
}

function validate(key, spec) {
  const problems = []
  const colors = spriteColors(spec.palette)
  for (const dir of SHEET_ROWS) {
    framesOf(spec, dir).forEach((rows, i) => {
      const name = `${key}.${dir}[${i}]`
      if (rows.length !== 16 || rows.some(r => r.length !== 16 || /[^.123]/.test(r))) {
        problems.push(`${name}: frames are 16 rows of 16 chars from ".123"`)
      }
      problems.push(...checkSprite(fromAscii(rows, colors), name))
    })
  }
  return problems
}

export function sheet(spec) {
  const colors = spriteColors(spec.palette)
  const b = new Bitmap(128, 128)
  SHEET_ROWS.forEach((dir, row) => {
    const frames = framesOf(spec, dir)
    FRAME_OF_COLUMN.forEach((f, col) => b.ascii(frames[f], colors, col * 32 + FIG_X, row * 32 + FIG_Y))
  })
  return b
}

export function characterAssets() {
  const problems = Object.entries(CHARACTERS).flatMap(([key, spec]) => validate(key, spec))
  if (problems.length) throw new Error(`Character sprites:\n  ${problems.join('\n  ')}`)
  return Object.entries(CHARACTERS).map(([key, spec]) => ({ out: key, bitmap: sheet(spec), kind: 'sprite' }))
}
