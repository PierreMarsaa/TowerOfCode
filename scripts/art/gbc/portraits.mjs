function pic({ colors, rows }, name) {
  if (rows.length !== 56 || rows.some(r => r.length !== 56)) throw new Error(`portrait ${name}: rows must be 56×56`)
  const stray = rows.join('').replace(/\./g, '').split('').find(ch => !colors[ch])
  if (stray) throw new Error(`portrait ${name}: '${stray}' is not in its palette`)
  return fromAscii(rows, colors)
}

